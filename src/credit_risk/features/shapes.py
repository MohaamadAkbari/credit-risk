"""How default risk moves with each feature, on the TRAINING fold only (Phase 2 review, finding 3).

For every stage C feature: default rate in up to ten quantile bins (missing values as their own
bin), information value (IV), and a shape:
  up / down   bin rates rise or fall almost steadily (Spearman |rho| >= 0.9 across bins)
  hump / U    rates rise then fall (or fall then rise) once, peaking / bottoming in an interior bin
  irregular   anything else, e.g. zig-zags from round loan amounts or common loan terms
  none        IV < 0.02: too little signal to have a shape
  categorical text feature: IV only
The shape gives the monotone-constraint suggestion for Phase 5 (+1 up, -1 down, 0 otherwise) and
tells the Phase 4 scorecard which features need non-monotone WoE bins.

Only the training fold is used, so these choices do not peek at validation or test.

Outputs: configs/feature_shapes.csv, reports/feature_shapes.md
Usage: python -m credit_risk.features.shapes   (or: make shapes)
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from credit_risk.paths import FEATURE_MANIFEST, PROCESSED

MIN_IV = 0.02
MONOTONE_RHO = 0.9


def woe_iv(bins: pd.Series, y: pd.Series) -> tuple[pd.DataFrame, float]:
    t = pd.crosstab(bins, y)
    t = t.reindex(columns=[0, 1], fill_value=0)
    good = (t[0] + 0.5) / (t[0].sum() + 0.5)
    bad = (t[1] + 0.5) / (t[1].sum() + 0.5)
    t["rate"] = t[1] / (t[0] + t[1])
    t["n"] = t[0] + t[1]
    return t, float(((good - bad) * np.log(good / bad)).sum())


def shape_of(rates: np.ndarray, iv: float) -> tuple[str, float]:
    if iv < MIN_IV:
        return "none", np.nan
    if len(rates) < 3:
        return ("up" if rates[-1] > rates[0] else "down"), np.nan
    rho = pd.Series(rates).corr(pd.Series(np.arange(len(rates))), method="spearman")
    if rho >= MONOTONE_RHO:
        return "up", rho
    if rho <= -MONOTONE_RHO:
        return "down", rho
    steps = np.diff(rates)
    signs = np.sign(steps[np.abs(steps) >= 0.005])             # ignore moves under half a point
    if (np.diff(signs) != 0).sum() > 1:                        # more than one turn: not a single hump or U
        return "irregular", rho
    lo, hi = int(np.argmin(rates)), int(np.argmax(rates))
    last = len(rates) - 1
    if 0 < hi < last and rates[hi] - max(rates[0], rates[last]) > 0.01:
        return "hump", rho
    if 0 < lo < last and min(rates[0], rates[last]) - rates[lo] > 0.01:
        return "U", rho
    return "irregular", rho


def analyse(x: pd.Series, y: pd.Series) -> dict:
    miss = x.isna()
    row = {"missing_pct": round(100 * miss.mean(), 1),
           "rate_if_missing": round(float(y[miss].mean()), 4) if miss.any() else np.nan,
           "rate_if_present": round(float(y[~miss].mean()), 4)}
    if not pd.api.types.is_numeric_dtype(x):
        _, iv = woe_iv(x.astype("object").fillna("MISSING"), y)
        return {**row, "iv": round(iv, 4), "shape": "categorical", "rho": np.nan, "monotone": 0, "bin_rates": ""}
    present = x[~miss]
    if present.nunique() <= 10:
        b = present
    else:
        b = pd.qcut(present, 10, duplicates="drop")
    t, _ = woe_iv(b, y[~miss])
    rates = t["rate"].to_numpy()
    all_bins = b.astype("object").reindex(x.index)
    all_bins = all_bins.where(~miss, "MISSING").astype(str)
    _, iv = woe_iv(all_bins, y)
    shape, rho = shape_of(rates, iv)
    return {**row, "iv": round(iv, 4), "shape": shape, "rho": round(rho, 3) if pd.notna(rho) else np.nan,
            "monotone": {"up": 1, "down": -1}.get(shape, 0),
            "bin_rates": " ".join(f"{100 * r:.1f}" for r in rates)}


def build(processed: Path, manifest: Path) -> pd.DataFrame:
    split = pd.read_parquet(processed / "split.parquet").set_index("SK_ID_CURR")
    train = split.index[split.fold == "train"]
    y = split.loc[train, "TARGET"].astype(int)
    X = pd.read_parquet(processed / "features_C.parquet").loc[train]
    block_of = {f: b for b, v in json.loads(manifest.read_text())["blocks"].items() for f in v["features"]}
    rows = [{"feature": c, "block": block_of.get(c, ""), **analyse(X[c], y)} for c in X.columns]
    return pd.DataFrame(rows).sort_values("iv", ascending=False).reset_index(drop=True)


def write_markdown(df: pd.DataFrame, path: Path, n_train: int) -> None:
    counts = df.shape_.value_counts() if "shape_" in df else df["shape"].value_counts()
    lines = [
        "# Feature shapes (training fold only)", "",
        f"*Generated by `make shapes` (`credit_risk.features.shapes`) on the {n_train:,} training-fold applicants; "
        "do not edit by hand. Machine-readable copy: `configs/feature_shapes.csv`.*", "",
        "**What it answers:** does default risk rise, fall, peak or do nothing as each feature grows? Phase 4 uses "
        "it to choose scorecard bins, Phase 5 to choose monotone constraints. Rates are per decile of the feature "
        "(fewer bins where values repeat); missing values are a separate bin in the information value (IV).", "",
        "IV reading, the usual credit-scoring rule of thumb: below 0.02 none, 0.02-0.1 weak, 0.1-0.3 medium, above 0.3 strong.", "",
        "## Count by shape", "",
        "| Shape | Features | Monotone constraint |", "| --- | --- | --- |",
        *[f"| {k} | {v} | {'+1' if k == 'up' else '-1' if k == 'down' else '0 (none)'} |" for k, v in counts.items()], "",
        "## All features, strongest first", "",
        "| Feature | Block | IV | Shape | Missing % | Default if missing | Default by decile, % (low to high value) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in df.itertuples():
        rm = "" if pd.isna(r.rate_if_missing) else f"{100 * r.rate_if_missing:.1f}%"
        lines.append(f"| `{r.feature}` | {r.block} | {r.iv:.3f} | {r.shape} | {r.missing_pct:g} | {rm} | {r.bin_rates} |")
    path.write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Shape and information value of each feature, training fold only.")
    ap.add_argument("--processed", default=PROCESSED, type=Path)
    ap.add_argument("--manifest", default=FEATURE_MANIFEST, type=Path)
    ap.add_argument("--out-csv", default=Path("configs/feature_shapes.csv"), type=Path)
    ap.add_argument("--out-md", default=Path("reports/feature_shapes.md"), type=Path)
    a = ap.parse_args(argv)
    df = build(a.processed, a.manifest)
    df.to_csv(a.out_csv, index=False)
    n = int((pd.read_parquet(a.processed / "split.parquet").fold == "train").sum())
    write_markdown(df, a.out_md, n)
    print(df["shape"].value_counts().to_dict())
    print(df.head(25)[["feature", "iv", "shape", "bin_rates"]].to_string())


if __name__ == "__main__":
    main()
